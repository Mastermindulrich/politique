// Generates supabase/seed/officials.sql from data/officials/*.json.
// Usage: node scripts/gen-officials-sql.mjs
//
// Each office is upserted on its stable office_key, so re-running after a
// reshuffle renames the office account to its new holder and keeps its
// followers, interpellations and the account that operates it (profile_id).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const ts = require("typescript");
const src = readFileSync(path.join(here, "../lib/ci-geo.ts"), "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { regions, departments, communes } = await import("data:text/javascript;base64," + Buffer.from(js).toString("base64"));

const norm = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]/g, "");
const regionId = (n) => { const r = regions.find((x) => norm(x.name) === norm(n)); if (!r) throw new Error(`unknown region ${n}`); return r.id; };
const departmentId = (n) => { const d = departments.find((x) => norm(x.name) === norm(n)); if (!d) throw new Error(`unknown department ${n}`); return d.id; };
const communeId = (n, depId, regId) => {
  const c = communes.filter((x) => norm(x.name) === norm(n) && (!depId || x.departmentId === depId) && (!regId || departments.find((d) => d.id === x.departmentId)?.regionId === regId));
  if (c.length !== 1) throw new Error(`commune ${n}: ${c.length} matches`);
  return c[0].id;
};

const q = (v) => (v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : "'" + String(v).replace(/'/g, "''") + "'");
const dir = path.join(here, "../data/officials");
const rows = [];
const areas = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const data = JSON.parse(readFileSync(path.join(dir, file), "utf8"));
  for (const o of data.offices) {
    const reg = o.region ? regionId(o.region) : null;
    const dep = o.department ? departmentId(o.department) : null;
    const com = o.commune ? communeId(o.commune, dep, reg) : null;
    for (const c of o.communes ?? []) areas.push([o.key, communeId(c, null, reg)]);
    rows.push({
      office_key: o.key,
      full_name: o.vacant ? "Poste vacant" : o.name,
      mandate: o.mandate,
      title: o.title,
      party: o.party ?? null,
      region_id: reg ?? (dep ? departments.find((d) => d.id === dep).regionId : null),
      department_id: com ? departments.find((d) => d.id === communes.find((c) => c.id === com).departmentId).id : dep,
      commune_id: com,
      circonscription: o.circonscription ?? o.sous_prefecture ?? null,
      institution: o.institution ?? data.institution,
      role: o.role ?? null,
      rank: o.rank ?? 1000,
      gender: o.gender ?? null,
      vacant: Boolean(o.vacant),
      note: o.note ?? null,
      source_url: o.source ?? data.source,
      source_label: data.source_label,
      source_checked: data.checked,
    });
  }
}
const keys = new Set();
for (const r of rows) { if (keys.has(r.office_key)) throw new Error(`duplicate key ${r.office_key}`); keys.add(r.office_key); }
// Regional prefects cover their whole region: keep region only.
for (const r of rows) if (r.mandate === "prefet" && r.role) r.department_id = null;

const cols = Object.keys(rows[0]);
const updatable = cols.filter((c) => c !== "office_key");
const chunks = [];
for (let i = 0; i < rows.length; i += 100) chunks.push(rows.slice(i, i + 100));
let out = "-- Generated by scripts/gen-officials-sql.mjs from data/officials/*.json. Do not edit by hand.\n";
out += "-- One statement per block so it can be applied piece by piece.\n";
for (const chunk of chunks) {
  out += `\ninsert into politique.officials (${cols.join(", ")}) values\n`;
  out += chunk.map((r) => `  (${cols.map((c) => (c === "mandate" ? `${q(r[c])}::politique.mandate_type` : c === "source_checked" ? `${q(r[c])}::date` : q(r[c]))).join(", ")})`).join(",\n");
  out += `\non conflict (office_key) do update set ${updatable.map((c) => `${c} = excluded.${c}`).join(", ")}, updated_at = now();\n`;
}
out += `\ndelete from politique.official_areas a using politique.officials o where o.id = a.official_id and o.office_key in (${[...new Set(areas.map((a) => a[0]))].map(q).join(", ")});\n`;
for (let i = 0; i < areas.length; i += 200) {
  const part = areas.slice(i, i + 200);
  out += `\ninsert into politique.official_areas (official_id, commune_id)\nselect o.id, v.commune_id from (values\n${part.map(([k, c]) => `  (${q(k)}, ${c})`).join(",\n")}\n) as v(office_key, commune_id) join politique.officials o on o.office_key = v.office_key\non conflict do nothing;\n`;
}
const dest = path.join(here, "../supabase/seed/officials.sql");
writeFileSync(dest, out);
console.log(`wrote ${dest}: ${rows.length} offices, ${areas.length} constituency communes`);
