// Generates supabase/seed/ci_geo.sql from lib/ci-geo.ts.
// Usage: node scripts/gen-geo-sql.mjs
import { writeFileSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const ts = require("typescript");

const src = readFileSync(path.join(here, "../lib/ci-geo.ts"), "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const mod = await import("data:text/javascript;base64," + Buffer.from(js).toString("base64"));
const { regions, departments, communes, slugify } = mod;

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
let out = "-- Generated by scripts/gen-geo-sql.mjs from lib/ci-geo.ts. Do not edit by hand.\n";
out += "insert into ci_regions (id, district, name, slug, is_autonomous_district) values\n";
out += regions.map((r) => `  (${r.id}, ${q(r.district)}, ${q(r.name)}, ${q(slugify(r.name))}, ${r.autonomous ? "true" : "false"})`).join(",\n");
out += "\non conflict (id) do update set district = excluded.district, name = excluded.name, slug = excluded.slug, is_autonomous_district = excluded.is_autonomous_district;\n\n";
out += "insert into ci_departments (id, region_id, name, slug) values\n";
out += departments.map((d) => `  (${d.id}, ${d.regionId}, ${q(d.name)}, ${q(slugify(d.name))})`).join(",\n");
out += "\non conflict (id) do update set region_id = excluded.region_id, name = excluded.name, slug = excluded.slug;\n\n";
out += "insert into ci_communes (id, department_id, name, slug) values\n";
out += communes.map((c) => `  (${c.id}, ${c.departmentId}, ${q(c.name)}, ${q(slugify(c.name))})`).join(",\n");
out += "\non conflict (id) do update set department_id = excluded.department_id, name = excluded.name, slug = excluded.slug;\n";

const dest = path.join(here, "../supabase/seed/ci_geo.sql");
writeFileSync(dest, out);
console.log(`wrote ${dest}: ${regions.length} regions, ${departments.length} departments, ${communes.length} communes`);
